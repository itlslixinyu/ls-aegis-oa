const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const vm = require('node:vm')
const { createRequire } = require('node:module')

const root = path.resolve(__dirname, '../..')
const webRequire = createRequire(path.join(root, 'ls-aegis-web/package.json'))
const ts = webRequire('typescript')
const cache = new Map()
function load(file) {
  if (cache.has(file)) return cache.get(file)
  const source = fs.readFileSync(path.join(root, 'ls-aegis-web/src', file), 'utf8')
  const code = ts.transpileModule(source, { compilerOptions: {
    module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true,
  } }).outputText
  const exports = {}
  vm.runInNewContext(code, { exports, Date, require: name => {
    if (name === 'cron-parser' || name === 'dayjs') return webRequire(name)
    if (name === '@/constant/datetime') return load('constant/datetime.ts')
    throw new Error(`Undeclared cron dependency: ${name}`)
  } }, { filename: file })
  cache.set(file, exports)
  return exports
}
const { getNextCronTimes, parseCron } = load('utils/cron.ts')
const clock = () => new Date(2026, 0, 1, 12, 0, 0)
const values = expression => Array.from(getNextCronTimes(expression, clock()))

test('six-field cron preview returns five local future dates', () => {
  assert.deepEqual(values('0 */15 * * * *'), [
    '2026-01-01 12:15:00', '2026-01-01 12:30:00', '2026-01-01 12:45:00',
    '2026-01-01 13:00:00', '2026-01-01 13:15:00',
  ])
})

test('five-field preview agrees with the equivalent zero-second expression', () => {
  assert.deepEqual(values('*/15 * * * *'), values('0 */15 * * * *'))
})

test('wildcard year generated by the editor preserves six-field results', () => {
  assert.deepEqual(values('0 */15 * * * * *'), values('0 */15 * * * *'))
})

test('cron whitespace does not alter scheduling fields', () => {
  assert.deepEqual(values('\t0   */15  * * * * \n'), values('0 */15 * * * *'))
})

test('invalid cron propagates to editor validation and gets readable list feedback', () => {
  assert.throws(() => getNextCronTimes('invalid-expression', clock()))
  assert.equal(parseCron('invalid-expression'), '表达式错误')
})

test('preview crosses calendar boundaries using the same display format', () => {
  assert.deepEqual(Array.from(getNextCronTimes('0 0 0 * * *', new Date(2026, 11, 31, 23, 59, 59))), [
    '2027-01-01 00:00:00', '2027-01-02 00:00:00', '2027-01-03 00:00:00',
    '2027-01-04 00:00:00', '2027-01-05 00:00:00',
  ])
  assert.equal(getNextCronTimes('0 0 0 * * *', new Date(2028, 1, 28, 23, 59, 59))[0], '2028-02-29 00:00:00')
})

test('calculating previews does not mutate the supplied clock', () => {
  const date = clock(), before = date.getTime()
  getNextCronTimes('0 */15 * * * *', date)
  assert.equal(date.getTime(), before)
})

test('explicit year never leaks executions from other years and may return fewer than five', () => {
  assert.deepEqual(values('0 0 0 1 1 * 2030'), ['2030-01-01 00:00:00'])
  assert.deepEqual(values('0 0 0 1 1 * 2020'), [])
})

test('year ranges, lists and intervals keep chronological order', () => {
  assert.deepEqual(values('0 0 0 1 1 * 2030-2032'), [
    '2030-01-01 00:00:00', '2031-01-01 00:00:00', '2032-01-01 00:00:00',
  ])
  assert.deepEqual(values('0 0 0 1 1 * 2032,2030,2030'), ['2030-01-01 00:00:00', '2032-01-01 00:00:00'])
  assert.deepEqual(values('0 0 0 1 1 * 2030/2'), [2030, 2032, 2034, 2036, 2038].map(y => `${y}-01-01 00:00:00`))
})

test('year windows handle leap dates, expiry and dense distant schedules', () => {
  assert.deepEqual(values('0 0 0 29 2 * 2027-2030'), ['2028-02-29 00:00:00'])
  assert.deepEqual(Array.from(getNextCronTimes('* * * * * * 2026', new Date(2026, 11, 31, 23, 59, 57))), [
    '2026-12-31 23:59:58', '2026-12-31 23:59:59',
  ])
  assert.deepEqual(values('* * * * * * 2099'), [0, 1, 2, 3, 4].map(s => `2099-01-01 00:00:0${s}`))
})

test('malformed year constraints and extra fields are rejected', () => {
  for (const year of ['2032-2030', '2030/0', '2030/no', '2030,', 'year', '10000', '1969']) {
    assert.throws(() => values(`0 0 0 1 1 * ${year}`), year)
  }
  assert.throws(() => values('0 0 0 1 1 * 2030 extra'))
})
